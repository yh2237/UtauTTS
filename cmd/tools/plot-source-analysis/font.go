func label(img *image.RGBA, x, y int, value string, ink color.RGBA, scale int) {
	value = strings.ToLower(value)
	value = strings.NewReplacer("ɕ", "sh", "ɯ", "u", "ɡ", "g", "ɴ", "n", "ɟ", "gy", "ə", "e", "ŋ", "ng", "ʔ", "q", "ɾ", "r", "ɸ", "f", "ː", ":").Replace(value)
	for _, r := range value {
		glyph, ok := glyphs[r]
		if !ok {
			glyph = glyphs['?']
		}
		for row, bits := range glyph {
			for col, ch := range bits {
				if ch == '#' {
					fill(img, x+col*scale, y+row*scale, x+(col+1)*scale, y+(row+1)*scale, ink)
				}
			}
		}
		x += 4 * scale
	}
}
