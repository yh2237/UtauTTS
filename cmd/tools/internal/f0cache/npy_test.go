package f0cache

import (
	"bytes"
	"encoding/hex"
	"math"
	"testing"
)

func TestLegacyNPYBytes(t *testing.T) {
	for _, tc := range []struct {
		alignment int
		x         []float64
		want      string
	}{
		{16, nil, "934e554d5059010046007b276465736372273a20273c6638272c2027666f727472616e5f6f72646572273a2046616c73652c20277368617065273a2028302c292c207d2020202020202020202020200a"},
		{64, nil, "934e554d5059010076007b276465736372273a20273c6638272c2027666f727472616e5f6f72646572273a2046616c73652c20277368617065273a2028302c292c207d2020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020200a"},
		{16, []float64{123.5, math.Copysign(0, -1)}, "934e554d5059010046007b276465736372273a20273c6638272c2027666f727472616e5f6f72646572273a2046616c73652c20277368617065273a2028322c292c207d2020202020202020202020200a0000000000e05e400000000000000080"},
		{64, []float64{123.5, math.Copysign(0, -1)}, "934e554d5059010076007b276465736372273a20273c6638272c2027666f727472616e5f6f72646572273a2046616c73652c20277368617065273a2028322c292c207d2020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020202020200a0000000000e05e400000000000000080"},
	} {
		var b bytes.Buffer
		if err := WriteNPY(&b, tc.x, tc.alignment); err != nil {
			t.Fatal(err)
		}
		if got := hex.EncodeToString(b.Bytes()); got != tc.want {
			t.Errorf("alignment %d, values %d: %s, want %s", tc.alignment, len(tc.x), got, tc.want)
		}
	}
}
